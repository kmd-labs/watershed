#!/usr/bin/env node
/**
 * Writes src/app/sea/sea-thumbs.ts — a small silhouette and the headline numbers of every sea's
 * drainage basin for the sea picker, so the picker can show all seas without downloading any.
 *
 *   node scripts/build-sea-thumbs.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SEAS = ['baltic', 'north', 'med', 'black', 'caspian'];
const TOL = 0.1; // degrees: a ~120 px card needs no more

function unpack([lens, b64], B) {
  const b = Buffer.from(b64, 'base64');
  const xy = new Uint16Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.length));
  const [L0, L1, A0, A1] = B.bbox;
  let o = 0;
  return lens.map(rl => rl.map(n => {
    const pts = [];
    for (let k = 0; k < n; k++, o++) pts.push([L0 + ((L1 - L0) * xy[o * 2]) / 65535, A0 + ((A1 - A0) * xy[o * 2 + 1]) / 65535]);
    return pts;
  }));
}

function dp(pts, tol) {
  // Closed rings (first = last) would give a zero-length base segment: open them first.
  if (pts.length > 1 && pts[0][0] === pts.at(-1)[0] && pts[0][1] === pts.at(-1)[1]) pts = pts.slice(0, -1);
  if (pts.length < 4) return pts;
  // Split at the vertex farthest from the first, so both halves have a real base segment.
  let far = 1, fd = 0;
  for (let i = 1; i < pts.length; i++) { const d = Math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]); if (d > fd) { fd = d; far = i; } }
  return [...dpOpen(pts.slice(0, far + 1), tol).slice(0, -1), ...dpOpen([...pts.slice(far), pts[0]], tol).slice(0, -1)];
}

function dpOpen(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let best = -1, dmax = 0;
    const [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][0] - x1) - dx * (pts[i][1] - y1)) / L;
      if (d > dmax) { dmax = d; best = i; }
    }
    if (dmax > tol && best > 0) { keep[best] = 1; stack.push([a, best], [best, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = r => { let s = 0; for (let i = 0, j = r.length - 1; i < r.length; j = i++) s += r[j][0] * r[i][1] - r[i][0] * r[j][1]; return s / 2; };

const out = {};
for (const sea of SEAS) {
  const B = JSON.parse(fs.readFileSync(path.join(root, `data/${sea}.source.json`), 'utf8'));
  const whole = unpack(B.outlines, B)[B.subs.length];
  // Outer rings only (the holes are lakes), large enough to be seen at card size.
  const sign = Math.sign(area(whole.reduce((a, r) => (Math.abs(area(r)) > Math.abs(area(a)) ? r : a))));
  const rings = whole.filter(r => Math.sign(area(r)) === sign && Math.abs(area(r)) > 0.2).map(r => dp(r, TOL)).filter(r => r.length >= 4);
  let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
  for (const r of rings) for (const [x, y] of r) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  const k = Math.cos((((y0 + y1) / 2) * Math.PI) / 180);
  const w = (x1 - x0) * k, h = y1 - y0, s = 100 / Math.max(w, h);
  const W = w * s, H = h * s;
  const d = rings.map(r => 'M' + r.map(([x, y]) => `${((x - x0) * k * s).toFixed(1)} ${((y1 - y) * s).toFixed(1)}`).join('L') + 'Z').join('');
  // The Baltic's people: HELCOM's figure, as on its poster (the new seas' come from GHSL).
  const pop = B.total.pop ?? (sea === 'baltic' ? 82_300_000 : undefined);
  out[sea] = { w: +W.toFixed(1), h: +H.toFixed(1), d, area: Math.round(B.total.parea), mouths: B.total.nout, ...(pop ? { pop } : {}) };
  console.log(sea, `${d.length} chars`);
}

const ts = `// Generated by scripts/build-sea-thumbs.mjs — do not edit.
import { SeaId } from '../core/sea';

/** Silhouette (SVG path in a w × h box) and headline numbers of each sea's drainage basin. */
export interface SeaThumb {
  w: number;
  h: number;
  d: string;
  /** km² */
  area: number;
  mouths: number;
  pop?: number;
}

export const SEA_THUMBS: Record<SeaId, SeaThumb> = ${JSON.stringify(out, null, 2)};
`;
fs.mkdirSync(path.join(root, 'src/app/sea'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/app/sea/sea-thumbs.ts'), ts);
console.log('wrote src/app/sea/sea-thumbs.ts', (ts.length / 1024).toFixed(1), 'KB');
